"""Expand project headers into reproducible C++20 judge submissions."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
INCLUDE = ROOT / "include"


def bundle(adapter: Path):
    seen, files = set(), {}

    def expand(path):
        path = path.resolve()
        if not path.is_relative_to(ROOT):
            raise ValueError("Source escapes project")
        if path in seen:
            return ""
        seen.add(path)
        data = path.read_bytes()
        relative = path.relative_to(ROOT).as_posix()
        files[relative] = hashlib.sha256(data).hexdigest()
        lines = [f"// begin {relative}"]
        depth = 0
        for line in data.decode("utf-8-sig").splitlines():
            if re.match(r"\s*#\s*(if|ifdef|ifndef)\b", line):
                depth += 1
            if re.match(r"\s*#\s*endif\b", line):
                depth -= 1
            match = re.fullmatch(r'\s*#\s*include\s*[<"]([^>"]+)[>"]\s*', line)
            if match and match[1].startswith("algorithm_assets/"):
                if depth:
                    raise ValueError("Conditional project includes are unsupported")
                child = (INCLUDE / match[1]).resolve()
                if not child.is_relative_to(INCLUDE):
                    raise ValueError("Header escapes include directory")
                lines.append(expand(child))
            elif match and '"' in line:
                raise ValueError("Non-project quoted includes are unsupported")
            elif re.match(r"\s*#\s*include\b", line) and "algorithm_assets/" in line:
                raise ValueError("Unsupported project include syntax")
            elif line.strip() != "#pragma once":
                lines.append(line)
        lines.append(f"// end {relative}")
        return "\n".join(lines) + "\n"

    code = "// Generated by tools/bundle_submission.py; C++20 required.\n" + expand(adapter)
    return code, {"adapter": adapter.relative_to(ROOT).as_posix(),
                  "sources_sha256": files,
                  "submission_sha256": hashlib.sha256(code.encode()).hexdigest()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "judge/generated"
    output.mkdir(parents=True, exist_ok=True)
    for adapter in sorted((ROOT / "judge/adapters").glob("*.cpp")):
        code, manifest = bundle(adapter)
        for path, content in ((output / adapter.name, code),
                              (output / (adapter.stem + ".json"), json.dumps(manifest, indent=2) + "\n")):
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != content:
                    raise SystemExit(f"Stale or missing generated file: {path.name}")
            else:
                path.write_text(content, encoding="utf-8", newline="\n")
    print("Judge bundles are current" if args.check else "Generated judge bundles and source hashes")


if __name__ == "__main__":
    main()
